"""Code-generated evaluation report (`docs/results.md`) from saved raw outputs (D27, D75).

Every number is computed directly from committed JSON files under `results/` and cites its
corresponding `R#N` entry in `RESULTS.md`.
"""

import json
from collections.abc import Iterable, Mapping
from pathlib import Path
from typing import Any

_EDGE_DIMS = (
    "scope_ok",
    "deadlines_ok",
    "counts_ok",
    "asks_ok",
    "cites_gold",
    "no_leak",
    "says_required",
    "avoids_forbidden",
)


def render_report(root: Path = Path(".")) -> str:
    """Render the full Markdown results report from saved `results/*.json`."""
    sections = [
        _header(),
        _retrieval_section(root),
        _extraction_section(root),
        _pipeline_and_answers_section(root),
        _edge_section(root),
        _audit_section(root),
    ]
    return "\n\n".join(sections).rstrip() + "\n"


def _load(path: Path) -> dict[str, Any]:
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise TypeError(f"{path} must contain a JSON object")
    return data


def _header() -> str:
    return "\n".join(
        [
            "# Niyam Evaluation Results",
            "",
            "> Generated by `uv run niyam eval-report docs/results.md` from committed raw files "
            "in `results/`. Every metric cites its `R#N` entry in `RESULTS.md`. Under **D75**, "
            "`R5`-`R15` are frozen as Niyam's v1 baselines, verified in CI by `niyam eval-gate`.",
        ]
    )


def _retrieval_section(root: Path) -> str:
    dev_hyde = _load(root / "results/retrieval-dev-1.json")
    dev_rerank = _load(root / "results/retrieval-dev-rerank-1.json")
    test_hyde = _load(root / "results/retrieval-test-1.json")
    test_rerank = _load(root / "results/retrieval-test-rerank-1.json")

    hdr = (
        "| Arm | hit@1 | hit@3 | hit@5 | MRR@10 | "
        "Paired 95% CI vs Vector (`hit@1` / `MRR@10`) | Source |"
    )
    sep = "|---|---:|---:|---:|---:|---|---|"
    lines = [
        "## 1. Retrieval Comparison (R7, R8, R9, R12)",
        "",
        "Gold is the regulation paragraph in 8 CFR 214.2(f) that answers the question. "
        "`Vector + Rerank` embeds queries with `gemini-embedding-2` (768-d) and reranks the "
        "top 10 vector candidates using `gemini-decision-1` (D49).",
        "",
        f"### Dev Split ({len(dev_rerank['rankings'])} questions: R7, R9)",
        "",
        hdr,
        sep,
        *_retrieval_rows(dev_hyde, dev_rerank, ("R7", "R9")),
        "",
        f"### Held-out Test Split ({len(test_rerank['rankings'])} questions: R8, R12)",
        "",
        hdr,
        sep,
        *_retrieval_rows(test_hyde, test_rerank, ("R8", "R12")),
        "",
        "- **Takeaway:** Plain vector search outperformed keyword and reciprocal-rank hybrid "
        "fusion (R4, R7, R8), while HyDE confidence intervals crossed zero. Adding "
        "`gemini-decision-1` reranking pushed `hit@1` to "
        f"`{dev_rerank['metrics']['vector+rerank']['hit@1']:.3f}` on dev (R9) and "
        f"`{test_rerank['metrics']['vector+rerank']['hit@1']:.3f}` on held-out test (R12, "
        f"95% CI `{_ci(test_rerank['versus_vector']['vector+rerank']['hit@1'])}`).",
        "- **R8 vs R12 baseline shift:** Held-out `vector` `hit@1` moved from "
        f"`{test_hyde['metrics']['vector']['hit@1']:.3f}` (R8) to "
        f"`{test_rerank['metrics']['vector']['hit@1']:.3f}` (R12) after D59 added "
        "`8 CFR 214.2(f)(10)(ii)(C)(2)` as a co-valid gold citation on `r19` (R16 gold audit). "
        "Note also that 20 of 60 dev items share a gold citation with the test set.",
    ]
    return "\n".join(lines)


def _retrieval_rows(
    hyde_run: Mapping[str, Any], rerank_run: Mapping[str, Any], refs: tuple[str, str]
) -> list[str]:
    r_hyde, r_rerank = refs
    order: list[tuple[str, str, Mapping[str, Any], str]] = [
        ("Keyword (Postgres FTS)", "keyword", rerank_run, r_rerank),
        ("Vector (`gemini-embedding-2`, 768-d)", "vector", rerank_run, r_rerank),
        ("Hybrid (RRF)", "hybrid", rerank_run, r_rerank),
        ("HyDE", "hyde", hyde_run, r_hyde),
        ("Vector + HyDE", "vector+hyde", hyde_run, r_hyde),
        ("Vector + Rerank (`gemini-decision-1`)", "vector+rerank", rerank_run, r_rerank),
    ]
    rows = []
    for label, arm, run, src in order:
        m = run["metrics"][arm]
        if arm == "vector":
            ci_cell = "baseline"
        else:
            vs = run["versus_vector"][arm]
            ci_cell = f"`{_ci(vs['hit@1'])}` / `{_ci(vs['mrr@10'])}`"
        rows.append(
            f"| {label} | {m['hit@1']:.3f} | {m['hit@3']:.3f} | {m['hit@5']:.3f} | "
            f"{m['mrr@10']:.3f} | {ci_cell} | {src} |"
        )
    return rows


def _ci(interval: Mapping[str, float]) -> str:
    return f"{interval['mean']:+.3f} [{interval['low']:+.3f}, {interval['high']:+.3f}]"


